import { build } from 'esbuild';
import { mkdir, writeFile } from 'node:fs/promises';
await mkdir('mobile/generated', { recursive: true });
const result = await build({
  entryPoints: ['viewer/runtime.js'],
  bundle: true,
  minify: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  alias: { vm: './viewer/no-vm.js' }});
const script = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const html = `<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data:; connect-src 'none'; worker-src 'none'; frame-src 'none';"><style>html,body{margin:0;width:100%;height:100%;overflow:hidden;background:#152225;touch-action:none}canvas{display:block;width:100%;height:100%}#error{color:#ffe3ba;font:14px sans-serif;padding:20px}</style></head><body><script>${script}</script></body></html>`;
await writeFile(
  'mobile/generated/viewerHtml.ts',
  `// Generated by npm run viewer:build. Fixed, bundled dependencies.\nexport const viewerHtml = ${JSON.stringify(html)};\n`);
await mkdir('artifacts', { recursive: true });
await writeFile('artifacts/viewer.html', html);
console.log('Bundled isolated viewer:', Math.round(html.length / 1024), 'KiB');
